#!/usr/bin/env python3
"""Generate the APM manifest for this root-layout skill package."""
import argparse
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "apm.yml"
VERSION = "1.0.0"
AUTHOR = "Lumel Technologies Inc."
TARGETS = ("agent-skills", "copilot", "codex", "claude")


def skill_metadata():
    text = (ROOT / "SKILL.md").read_text(encoding="utf-8")
    match = re.match(r"\A---\n(.*?)\n---\n", text, re.S)
    if not match:
        raise ValueError("SKILL.md must start with YAML frontmatter")
    fields = {}
    for line in match.group(1).splitlines():
        key, separator, value = line.partition(":")
        if separator:
            fields[key.strip()] = value.strip()
    name = fields.get("name", "")
    description = fields.get("description", "")
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
        raise ValueError("SKILL.md name must use lowercase letters, numbers and hyphens")
    if not description:
        raise ValueError("SKILL.md description is required")
    first_sentence = description.split(". ", 1)[0].rstrip(".") + "."
    return name, first_sentence


def render_manifest():
    name, description = skill_metadata()
    lines = [
        "# Generated by build/gen_apm_manifests.py -- do not edit by hand.",
        "#",
        f"#     apm install lumeltech/fabric-plan-skill --skill {name}",
        "#",
        f"name: {name}",
        f"version: {VERSION}",
        f"description: {description}",
        f"author: {AUTHOR}",
        "license: MIT",
        "targets:",
        *(f"  - {target}" for target in TARGETS),
        "scripts:",
        "  test: python scripts/plan.py test",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if apm.yml is not current")
    args = parser.parse_args()
    expected = render_manifest().encode("utf-8")
    if args.check:
        if not MANIFEST.is_file() or MANIFEST.read_bytes() != expected:
            print("apm.yml is missing or stale; run build/gen_apm_manifests.py", file=sys.stderr)
            return 1
        return 0
    MANIFEST.write_bytes(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
